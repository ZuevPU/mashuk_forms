EMAIL_RE = re.compile(r"^[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}$")


def digits_only(value: str) -> str:
    return re.sub(r"\D", "", value or "")


def valid_email(value: str) -> bool:
    s = (value or "").strip()
    if not s or len(s) > 254 or ".." in s:
        return False
    return bool(EMAIL_RE.fullmatch(s))


def valid_snils(value: str) -> bool:
    digits = digits_only(value)
    if len(digits) != 11:
        return False
    if digits == "00000000000":
        return False
    number = int(digits[:9])
    if number < 1001998:
        return True
    checksum = sum(int(digits[i]) * (9 - i) for i in range(9))
    if checksum < 100:
        check = checksum
    elif checksum in (100, 101):
        check = 0
    else:
        check = checksum % 101
        if check == 100:
            check = 0
    return check == int(digits[9:11])


def _inn_ctrl(digits: str, coeffs: list[int]) -> str:
    total = sum(int(digits[i]) * coeffs[i] for i in range(len(coeffs)))
    return str((total % 11) % 10)


def valid_inn(value: str) -> bool:
    digits = digits_only(value)
    if len(digits) != 12 or len(set(digits)) == 1:
        return False
    n11 = _inn_ctrl(digits, [7, 2, 4, 10, 3, 5, 9, 4, 6, 8])
    n12 = _inn_ctrl(digits, [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8])
    return n11 == digits[10] and n12 == digits[11]


def normalize_district(value: str) -> str:
    s = " ".join((value or "").split())
    return DISTRICT_ALIASES.get(s, s)
